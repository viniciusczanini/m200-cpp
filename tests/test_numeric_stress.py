"""Local numeric properties with answers independent of m200.numeric.evaluate.

Fixed answers cover the complete public intrinsic catalogue. Seeded integer
vectors use Python integers and bit strings as a separate reference. Native
checks observe result bits through public word-memory aliases; Machine memory
is also checked directly so a shared comparison bug cannot hide a wrong value.
"""

