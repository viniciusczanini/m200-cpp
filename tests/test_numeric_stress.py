@dataclass(frozen=True)
class Vector:
    operation: str
    kind: str
    arguments: tuple
    expected: object


def real32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]


def raw_bits(value, kind):
    if kind == "f32":
        return struct.unpack("<I", struct.pack("<f", value))[0]
    return value % (1 << (16 if kind == "i16" else 32))


def signed(value, width):
    value %= 1 << width
    return value if value < 1 << (width - 1) else value - (1 << width)


def cpp_literal(value, kind):
    if kind != "f32":
        return str(value)
    text = format(real32(value), ".9g")
    if "." not in text and "e" not in text.lower():
        text += ".0"
    return text + "f"


def argument_kind(operation, index):
    if operation in ("int_to_real",):
        return "i16"
    if operation in ("dint_to_real", "low_word", "high_word"):
        return "i32"
    if operation in ("real_to_int", "real_to_dint"):
        return "f32"
    if operation.startswith(("shl_", "shr_", "rol_", "ror_")) and index == 1:
        return "count"
    return operation.rsplit("_", 1)[1]


