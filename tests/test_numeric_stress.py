def integer_answer(operation, left, right, width):
    """Independent mathematical/bit-string oracle, with unbounded Python ints."""
    if operation == "add":
        return left + right
    if operation == "sub":
        return left - right
    if operation == "mul":
        return left * right
    if operation in ("div", "rem"):
        quotient, _ = divmod(abs(left), abs(right))
        if (left < 0) ^ (right < 0):
            quotient = -quotient
        return quotient if operation == "div" else left - quotient * right
    bits = format(left % (1 << width), "0%db" % width)
    if operation == "shl":
        result = bits[right:] + "0" * right
    elif operation == "shr":
        result = "0" * right + bits[: width - right]
    elif operation == "rol":
        result = bits[right:] + bits[:right]
    elif operation == "ror":
        result = bits[width - right :] + bits[: width - right]
    else:
        raise AssertionError("unknown independent oracle operation")
    return signed(int(result, 2), width)


class NumericStressTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="m200-numeric-stress-")
        self.addCleanup(self.tmp.cleanup)
        self.work = Path(self.tmp.name)

    def source(self, name, body):
        source = self.work / (name + ".cpp")
        source.write_text("#include <plc.hpp>\n" + body)
        return source

    def assert_vectors(self, vectors, recompile=False):
        # Eight outputs keep each compilation small and exercise every result
        # independently instead of collapsing a batch into one boolean answer.
        for first in range(0, len(vectors), 8):
            batch = vectors[first : first + 8]
            statements = []
            for slot, vector in enumerate(batch):
                arguments = ",".join(
                    cpp_literal(value, argument_kind(vector.operation, index))
                    for index, value in enumerate(vector.arguments)
                )
                address = slot * 2
                writer = {"i16": "word", "i32": "dword", "f32": "real"}[vector.kind]
                statements.append(
                    "plc::write_%s(%d,plc::%s(%s));"
                    % (writer, address, vector.operation, arguments)
                )
                if vector.kind == "f32":
                    reader = "dword"
                    expected = signed(raw_bits(vector.expected, "f32"), 32)
                else:
                    reader = writer
                    expected = vector.expected
                statements.append(
                    "plc::output(%d,plc::read_%s(%d)==%s);"
                    % (slot, reader, address, expected)
                )
            source = self.source(
                "vectors_%03d" % first, "void scan(){\n" + "\n".join(statements) + "\n}"
            )
            program = compile_source(source)
            machine = Machine(program)
            frames = [{"dt_ms": 0}, {"dt_ms": 1}, {"dt_ms": 17}]
            emitted = [machine.step({}, frame["dt_ms"]) for frame in frames]
            expected_outputs = [True] * len(batch) + [False] * (16 - len(batch))
            self.assertEqual(emitted, [expected_outputs] * len(frames), batch)
            for slot, vector in enumerate(batch):
                with self.subTest(vector=vector):
                    raw = machine.words[slot * 2]
                    if vector.kind != "i16":
                        raw |= machine.words[slot * 2 + 1] << 16
                    self.assertEqual(raw, raw_bits(vector.expected, vector.kind))
            self.assertEqual(run_native(source, frames), emitted, batch)
            reverse = self.work / ("reverse_%03d.cpp" % first)
            reverse.write_text(to_cpp(program))
            self.assertEqual(run_native(reverse, frames), emitted, batch)
            if recompile:
                rebuilt = Machine(compile_source(reverse))
                self.assertEqual(
                    [rebuilt.step({}, frame["dt_ms"]) for frame in frames],
                    emitted,
                    batch,
                )

    def test_all_intrinsics_match_declared_answers_and_roundtrip(self):
        vectors = fixed_vectors()
        self.assertEqual({vector.operation for vector in vectors}, set(OPS))
        self.assert_vectors(vectors, recompile=True)

    def test_seeded_integer_vectors_match_independent_oracle(self):
        rng = random.Random(0x200CE40)
        vectors = []
        for width in (16, 32):
            kind = "i%d" % width
            for index in range(32):
                stem = ("add", "sub", "mul", "div", "rem")[index % 5]
                if stem == "mul":
                    bound = 100 if width == 16 else 20000
                elif stem in ("div", "rem"):
                    bound = (1 << (width - 1)) - 1
                else:
                    bound = 10000 if width == 16 else 1000000000
                left = rng.randint(-bound, bound)
                right = (
                    rng.choice((-17, -3, -1, 1, 2, 7))
                    if stem in ("div", "rem")
                    else rng.randint(-bound, bound)
                )
                expected = integer_answer(stem, left, right, width)
                vectors.append(Vector(stem + "_" + kind, kind, (left, right), expected))
            for stem in ("shl", "shr", "rol", "ror"):
                for count in (1, width - 1, width):
                    left = rng.randint(-(1 << (width - 1)), (1 << (width - 1)) - 1)
                    vectors.append(
                        Vector(
                            stem + "_" + kind,
                            kind,
                            (left, count),
                            integer_answer(stem, left, count, width),
                        )
                    )
        self.assert_vectors(vectors)

